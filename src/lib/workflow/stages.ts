export function getStageById(id: string): WorkflowStage | undefined {
  return WORKFLOW_STAGES.find((s) => s.id === id);
}

export function getAdjacentStages(id: WorkflowStageId): {
  previous: WorkflowStage | null;
  next: WorkflowStage | null;
} {
  const index = WORKFLOW_STAGES.findIndex((s) => s.id === id);
  return {
    previous: index > 0 ? WORKFLOW_STAGES[index - 1] : null,
    next: index >= 0 && index < WORKFLOW_STAGES.length - 1 ? WORKFLOW_STAGES[index + 1] : null,
  };
}
